; dsrestore.s - the end of software/evkae_ds.bin (built by mkdsimage.py).
;
; The file is a memory image of the VAX 8600 Diagnostic Supervisor taken
; from simh vax8600 at its DS> prompt, with a diagnostic (EVKAE unless
; mkdsimage.py was told otherwise) already loaded, followed by this code. Loaded at 0 and started at 200 (the OSD settings for EVKAA), it
; comes here through a jump that replaced the first bytes at 200, puts those
; bytes back, loads the internal registers simh had, prints the prompt and
; returns to the supervisor with REI. The supervisor runs with memory
; management off at its prompt, so everything here is physical.
;
; Generated by mkdsimage.py: dsstate.inc defines FINISH (where this goes)
; and the S_xxx values, orig200.inc holds the 256 bytes that were at 200,
; dsmsg.inc the banner.

	.include "dsstate.inc"

KSP	= 0
ESP	= 1
SSP	= 2
USP	= 3
ISP	= 4
P0BR	= 8
P0LR	= 9
P1BR	= ^xA
P1LR	= ^xB
SBR	= ^xC
SLR	= ^xD
PCBB	= ^x10
SCBB	= ^x11
IPL	= ^x12
ASTLVL	= ^x13
SIRR	= ^x14
ICCS	= ^x18
NICR	= ^x19
RXCS	= ^x20
TXCS	= ^x22
TXDB	= ^x23
MAPEN	= ^x38
TBIA	= ^x39

	.org	FINISH
fin:	mtpr	#^x1F, #IPL
	mtpr	#0, #MAPEN
	mtpr	#0, #TBIA
	movc3	#^x100, orig200, @#^x200	; what the jump at 200 replaced
	mtpr	#S_SBR, #SBR
	mtpr	#S_SLR, #SLR
	mtpr	#S_P0BR, #P0BR
	mtpr	#S_P0LR, #P0LR
	mtpr	#S_P1BR, #P1BR
	mtpr	#S_P1LR, #P1LR
	mtpr	#S_SCBB, #SCBB
	mtpr	#S_PCBB, #PCBB
	mtpr	#S_ASTLVL, #ASTLVL
	mtpr	#S_KSP, #KSP
	mtpr	#S_ESP, #ESP
	mtpr	#S_SSP, #SSP
	mtpr	#S_USP, #USP
	mtpr	#S_NICR, #NICR
	mtpr	#S_ICCS, #ICCS			; RUN/IE as simh had them, ICR <- NICR
	mtpr	#S_RXCS, #RXCS
	mtpr	#S_TXCS, #TXCS
	movl	#S_SISR, r2			; pending software interrupts:
	movl	#1, r3				; request them again through SIRR
sisr1:	bbc	r3, r2, sisr2
	mtpr	r3, #SIRR
sisr2:	aobleq	#15, r3, sisr1
	movab	msg, r1				; the banner, by polling
msg1:	movzbl	(r1)+, r0
	beql	msg3
msg2:	mfpr	#TXCS, r2
	bbc	#7, r2, msg2
	mtpr	r0, #TXDB
	brb	msg1
msg3:	mtpr	#S_ISP-8, #ISP			; on the interrupt stack: SP too
	movl	#S_PC, (sp)
	movl	#S_PSL, 4(sp)
	movl	#S_R0, r0
	movl	#S_R1, r1
	movl	#S_R2, r2
	movl	#S_R3, r3
	movl	#S_R4, r4
	movl	#S_R5, r5
	movl	#S_R6, r6
	movl	#S_R7, r7
	movl	#S_R8, r8
	movl	#S_R9, r9
	movl	#S_R10, r10
	movl	#S_R11, r11
	movl	#S_AP, ap
	movl	#S_FP, fp
	rei					; to the supervisor

msg:						; the banner, ending in "DS> "
	.include "dsmsg.inc"
	.align	4
orig200:
	.include "orig200.inc"
