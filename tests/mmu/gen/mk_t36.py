#!/usr/bin/env python3
# mk_t36.py - generates tests/mmu/t36_editpc.s, EDITPC with random patterns (seed, count):
#     python3 tests/mmu/gen/mk_t36.py [seed] [count] > tests/mmu/t36_editpc.s
# The expected values are not in the test: run.py compares them with the
# reference simulator's.
import random, sys
seed = int(sys.argv[1]) if len(sys.argv) > 1 else 1
ncase = int(sys.argv[2]) if len(sys.argv) > 2 else 60
random.seed(seed)

def packed(n, sign=None):
    if sign is None:
        sign = random.choice([0xC, 0xD, 0xC, 0xD, 0xB, 0xF])
    digits = [random.randint(0, 9) for _ in range(n)]
    r = random.random()
    if r < 0.15:
        digits = [0] * n
    elif r < 0.5 and n > 2:
        k = random.randint(1, n)
        digits = [0] * (n - k) + digits[n - k:]
    nib = digits + [sign]
    if n % 2 == 0:
        nib = [0] + nib
    return bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))

def pattern(n):
    """a valid pattern for an n-digit source"""
    p = []
    left = n
    written = 0
    if random.random() < 0.4:
        t = random.randint(1, 31)
        p += [0x47, t]
        left = t
    def filler():
        nonlocal written
        op = random.choice(['ins', 'ldf', 'lds', 'ldp', 'ldm', 'sets', 'clrs', 'stsg', 'endf', 'fill', 'blz', 'rps'])
        if op == 'ins':
            p.extend([0x44, random.choice(b',.$/-')]); written += 1
        elif op == 'ldf':
            p.extend([0x40, random.choice(b'*# ')])
        elif op == 'lds':
            p.extend([0x41, random.choice(b'+-$')])
        elif op == 'ldp':
            p.extend([0x42, random.choice(b'+ ')])
        elif op == 'ldm':
            p.extend([0x43, random.choice(b'-CD')])
        elif op == 'sets':
            p.append(0x03)
        elif op == 'clrs':
            p.append(0x02)
        elif op == 'stsg':
            p.append(0x04); written += 1
        elif op == 'endf':
            p.append(0x01); written += 1	# at most one character
        elif op == 'fill':
            r = random.randint(1, 4); p.append(0x80 | r); written += r
        elif op == 'blz' and written > 0:
            p.extend([0x45, random.randint(1, written)])
        elif op == 'rps' and written > 0:
            p.extend([0x46, random.randint(1, written)])
    while left > 0:
        if random.random() < 0.5:
            filler()
        r = random.randint(1, min(15, left))
        op = random.choice([0x90, 0xA0, 0x90])
        p.append(op | r)
        written += r + (1 if op == 0xA0 else 0)
        left -= r
    if random.random() < 0.5:
        filler()
    p.append(0x00)
    return p

lines, datas = [], []
dn = [0]
def data(b):
    lab = 'd%d' % dn[0]; dn[0] += 1
    datas.append('%s:\t.byte\t%s' % (lab, ', '.join('^x%02X' % x for x in b)))
    return lab

classic = [
    # simple: MOVE all digits
    (5, [0x95, 0x00]),
    # check protection: fill '*', float sign, insert comma
    (7, [0x40, 0x2A, 0x43, 0x2D, 0xA4, 0x44, 0x2C, 0xA3, 0x00]),
    # blank when zero
    (4, [0x94, 0x45, 0x04, 0x00]),
    # leading zeros supplied
    (3, [0x47, 0x06, 0x96, 0x00]),
    # digits dropped
    (8, [0x47, 0x03, 0x93, 0x00]),
    # end float, store sign
    (6, [0xA6, 0x01, 0x04, 0x00]),
]
cases = []
for n, pat in classic:
    cases.append((n, packed(n), pat))
for i in range(ncase):
    n = random.choice([random.randint(0, 31), random.randint(1, 10)])
    cases.append((n, packed(n), pattern(n)))

for n, src, pat in cases:
    s = data(src); p = data(bytes(pat))
    psw = random.choice([0, 0, 0x80, 0x0F])
    lines.append('; EDITPC %d digits, pattern %s' % (n, ' '.join('%02X' % x for x in pat)))
    lines.append('\tmovc5\t#0, @#S0+^x1C000, #^x55, #64, @#S0+^x1C000')
    for r in range(6):
        lines.append('\tmovl\t#^x%X, r%d' % (0x11111111 * (r + 1), r))
    lines.append('\tbicpsw\t#^xFF')
    if psw:
        lines.append('\tbispsw\t#^x%X' % psw)
    lines.append('\teditpc\t#%d, @#S0+%s, @#S0+%s, @#S0+^x1C000' % (n, s, p))
    lines.append('\tmovpsl\t(r11)+')
    lines.append('\tmovq\tr0, (r11)+')
    lines.append('\tmovq\tr2, (r11)+')
    lines.append('\tmovq\tr4, (r11)+')
    lines.append('\tmovc3\t#48, @#S0+^x1C000, (r11)')
    lines.append('\tmovl\tr3, r11')

out = ["""; t36_editpc - EDITPC with a few classic patterns and random ones (seed
; %d): every operator, leading zeros supplied and digits dropped by
; EO$ADJUST_INPUT, PSL<DV> (decimal overflow trap). Each case logs the PSL,
; R0-R5 and the destination. Generated by mk_t36.py; compared with the
; reference simulator.
;@ dump=18000:C00 clocks=8000000
	.include "mmsetup.inc"
test:
	movl	#S0+arith_h, @#^x34
""" % seed]
out += lines
out.append('\thalt')
out.append("""	.align	4
arith_h:
	movl	#^x34, (r11)+
	movl	(sp)+, (r11)+
	movl	(sp), (r11)+
	movl	4(sp), (r11)+
	rei
""")
out += datas
sys.stdout.write('\n'.join(out) + '\n')
