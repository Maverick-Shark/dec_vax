#!/usr/bin/env python3
"""
mkfont.py - build rtl/mister/vt_font.v (8x16 glyph ROM) from a BDF font.

Default font: Spleen 8x16 (BSD 2-Clause, https://github.com/fcambus/spleen).

ROM layout (256 glyphs x 16 rows, address = {glyph[7:0], row[3:0]}):
  00h-1Fh  DEC Special Graphics for characters 5Fh-7Eh (VT100 "ESC ( 0")
  20h-7Eh  ASCII
  7Fh-9Fh  blank
  A0h-FFh  ISO Latin-1 (close to DEC MCS)

Usage:  python3 tools/mkfont.py spleen-8x16.bdf rtl/mister/vt_font.v
"""
import sys

DEC_GFX = [0x00A0, 0x25C6, 0x2592, 0x2409, 0x240C, 0x240D, 0x240A, 0x00B0,
           0x00B1, 0x2424, 0x240B, 0x2518, 0x2510, 0x250C, 0x2514, 0x253C,
           0x23BA, 0x23BB, 0x2500, 0x23BC, 0x23BD, 0x251C, 0x2524, 0x2534,
           0x252C, 0x2502, 0x2264, 0x2265, 0x03C0, 0x2260, 0x00A3, 0x00B7]

# scan-line glyphs synthesised if the font lacks them (row of the line)
SCANLINE = {0x23BA: 0, 0x23BB: 4, 0x23BC: 11, 0x23BD: 15}


def parse_bdf(path):
    glyphs, asc = {}, 12
    lines = open(path, encoding="latin-1").read().splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith("FONT_ASCENT"):
            asc = int(ln.split()[1])
        if ln.startswith("STARTCHAR"):
            enc, bbx, bits = None, None, []
            while not lines[i].startswith("ENDCHAR"):
                t = lines[i].split()
                if t and t[0] == "ENCODING":
                    enc = int(t[1])
                elif t and t[0] == "BBX":
                    bbx = tuple(int(v) for v in t[1:5])
                elif t and t[0] == "BITMAP":
                    i += 1
                    while not lines[i].startswith("ENDCHAR"):
                        bits.append(int(lines[i], 16))
                        i += 1
                    break
                i += 1
            if enc is not None and bbx is not None:
                w, h, xo, yo = bbx
                rows = [0] * 16
                top = asc - (yo + h)
                nbytes = (w + 7) // 8
                for k, v in enumerate(bits):
                    r = top + k
                    if 0 <= r < 16:
                        byte = (v >> (8 * (nbytes - 1))) & 0xFF
                        rows[r] = (byte >> xo) & 0xFF
                glyphs[enc] = rows
        i += 1
    return glyphs


def main():
    src, dst = sys.argv[1], sys.argv[2]
    g = parse_bdf(src)
    blank = [0] * 16
    table, missing = [], []
    for code in range(256):
        if code < 0x20:
            u = DEC_GFX[code]
            if u in g:
                rows = g[u]
            elif u == 0x2260 and ord("=") in g:     # not-equal: '=' plus a slash
                rows = list(g[ord("=")])
                for r in range(3, 13):
                    rows[r] |= 0x80 >> (6 - (r - 3) * 6 // 9)
            elif u in SCANLINE:
                rows = [0xFF if r == SCANLINE[u] else 0 for r in range(16)]
            else:
                rows = blank
                missing.append(hex(u))
        elif code < 0x7F or code >= 0xA0:
            rows = g.get(code, blank)
            if code not in g:
                missing.append(hex(code))
        else:
            rows = blank
        table.append(rows)

    with open(dst, "w") as f:
        f.write("// vt_font.v - 8x16 glyph ROM, generated by tools/mkfont.py from\n")
        f.write("// Spleen 8x16 (c) 2018-2026 Frederic Cambus, BSD 2-Clause license:\n")
        f.write("//   https://github.com/fcambus/spleen  (see LICENSE.spleen)\n")
        f.write("// Glyphs 00h-1Fh hold the VT100 DEC Special Graphics set.\n")
        f.write("// DO NOT EDIT - regenerate with tools/mkfont.py\n\n")
        f.write("`default_nettype none\n\n")
        f.write("module vt_font (\n\tinput            clk,\n\tinput     [11:0] addr,\n"
                "\toutput reg [7:0] q\n);\n\n")
        f.write("\talways @(posedge clk)\n\t\tcase (addr)\n")
        for code, rows in enumerate(table):
            for r, v in enumerate(rows):
                if v:
                    f.write("\t\t12'h%03X: q <= 8'h%02X;\n" % (code * 16 + r, v))
        f.write("\t\tdefault: q <= 8'h00;\n\t\tendcase\n\nendmodule\n\n`default_nettype wire\n")
    print("glyphs written: 256, missing:", " ".join(missing) or "none")


if __name__ == "__main__":
    main()
