#!/usr/bin/env python3
"""mk_optable.py - regenerate vax_optable.py from simh's VAX decode table.

Usage: python3 tools/mk_optable.py <open-simh>/VAX/vax_sys.c > tools/vax_optable.py

The table lists, for every opcode the VAX architecture defines, its mnemonic
and its operand specifiers (access type + data type, as in the VAX
Architecture Reference Manual: r/m/w/a/v/b + b/w/l/q/o/f/d/g/h). It is only
data; simh (open-simh, Supnik's MIT-style licence) is where it is read from.
"""
import re
import sys

src = open(sys.argv[1]).read().split('\n')
start = next(i for i, l in enumerate(src) if l.startswith('const uint16 drom[NUM_INST]'))
rows, skip = [], False
for l in src[start + 1:]:
    if l.startswith('};'):
        break
    s = l.strip()
    if s.startswith('#if'):
        skip = True
        continue
    if s.startswith('#else') or s.startswith('#endif'):
        skip = False
        continue
    if skip or not l.startswith('{'):
        continue
    body = l[1:l.index('}')]
    fields = [f.strip() for f in body.split(',')]
    rows.append(fields)
txt = '\n'.join(src)
m = re.search(r'char const \* const opcode\[\] = \{(.*?)\};', txt, re.S)
names = [t.strip('"') if t != 'NULL' else None
         for t in re.findall(r'"[^"]*"|NULL', m.group(1))]
assert len(rows) == 512 and len(names) >= 512, (len(rows), len(names))

SPEC = {
    'RB': 'rb', 'RW': 'rw', 'RL': 'rl', 'RQ': 'rq', 'RO': 'ro',
    'MB': 'mb', 'MW': 'mw', 'ML': 'ml', 'MQ': 'mq', 'MO': 'mo',
    'AB': 'ab', 'AW': 'aw', 'AL': 'al', 'AQ': 'aq', 'AO': 'ao',
    'WB': 'wb', 'WW': 'ww', 'WL': 'wl', 'WQ': 'wq', 'WO': 'wo',
    'VB': 'vb', 'RF': 'rf', 'RD': 'rd', 'RG': 'rg', 'RH': 'rh',
    'BB': 'bb', 'BW': 'bw',
}
out = {}
for i, (f, n) in enumerate(zip(rows, names)):
    if not n or 'IG_RSVD' in f[0] or f[0] == '0':
        continue
    specs = [SPEC[x] for x in f[1:] if x != '0']
    code = i if i < 256 else 0xFD00 | (i - 256)
    out[n] = (code, specs)
print('# Generated by tools/mk_optable.py from simh VAX/vax_sys.c - do not edit.')
print('# mnemonic: (opcode, [operand specifiers])')
print('OPTABLE = {')
for n in sorted(out, key=lambda k: out[k][0]):
    print('    %-8r: (0x%04X, %r),' % (n, out[n][0], out[n][1]))
print('}')
